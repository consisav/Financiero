--   Puede ejecutarse de nuevo: la segunda vez solo actualiza.
-- Se ejecuta después del script 93.

create table if not exists public.compra_documentos_banco (
  id                  bigint generated always as identity primary key,
  compra_id           bigint not null references public.compras (id) on delete cascade,
  tipo                text not null check (tipo in ('CHEQUE', 'NOTA')),
  cuenta_bancaria_id  bigint references public.cuentas_bancarias (id),
  cuenta_bancaria     text not null default '',
  numero              integer not null,
  liquidacion         integer not null default 1,
  valor               numeric(18,2),
  tipo_documento      text,
  movimiento_id       bigint references public.movimientos_bancarios (id) on delete set null,
  creado_en           timestamptz not null default now(),
  unique (compra_id, tipo, cuenta_bancaria, numero, liquidacion)
);
create index if not exists compra_documentos_banco_cuenta_idx on public.compra_documentos_banco (cuenta_bancaria_id, tipo, numero);
alter table public.compra_documentos_banco enable row level security;
drop policy if exists "compra_documentos_banco: leer" on public.compra_documentos_banco;
