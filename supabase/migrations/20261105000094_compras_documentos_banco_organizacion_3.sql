  from m_docs_c m where m.cuenta is not null and not exists (select 1 from public.cuentas_bancarias b where b.localidad_id = m.loc_id and b.numero = m.cuenta);

  with x as (
    insert into public.compra_documentos_banco (compra_id, tipo, cuenta_bancaria_id, cuenta_bancaria, numero, liquidacion, valor, tipo_documento)
    select m.compra_id, m.tipo, (select b.id from public.cuentas_bancarias b where b.localidad_id = m.loc_id and b.numero = m.cuenta limit 1),
           coalesce(m.cuenta, ''), m.numero, coalesce(m.liquidacion, 1), m.valor, m.tipo_docto
    from m_docs_c m where m.compra_id is not null
    on conflict (compra_id, tipo, cuenta_bancaria, numero, liquidacion) do update set
      cuenta_bancaria_id = excluded.cuenta_bancaria_id, valor = excluded.valor, tipo_documento = excluded.tipo_documento
    returning (xmax = 0) as nuevo)
  select count(*) filter (where nuevo), count(*) filter (where not nuevo) into v_nuevos, v_act from x;

  raise notice '%', format('Cheques y notas de las compras de la organización 3: %s nuevos, %s actualizados.%s%s',
    v_nuevos, v_act,
    case when v_sin_compra > 0 then format(' %s documentos de compras que no existen (omitidos).', v_sin_compra) else '' end,
    case when v_sin_cuenta is not null then ' Cuentas bancarias que no existen (queda su número): ' || v_sin_cuenta || '.' else '' end);
  drop table m_docs;
  drop table m_docs_c;
end;
