--   Es la relación del sistema anterior entre cada compra y los documentos bancarios (cheques y notas de
--   crédito o débito) que la liquidaron. Tabla nueva compra_documentos_banco (no existía): compra, tipo
--   (CHEQUE o NOTA), cuenta bancaria (ligada por su número en la localidad; el número queda guardado),
--   número del cheque o de la nota, número de liquidación, valor liquidado y tipo de documento (TIPO_DOCTO).
--   Queda lista para ligarse con los movimientos bancarios cuando se migren los cheques y las notas (Caja y
--   Bancos); mientras tanto, como los documentos de liquidación (script 92), NO cambia el saldo de las
--   compras.
--   1. Un documento que ya existe (misma compra, tipo, cuenta, número y liquidación) se actualiza; si no, se crea.
