  compra_anterior integer not null,
  compra_id bigint references public.compras(id) on delete set null,
  vinculo text not null check (vinculo in ('COMPRA_REF', 'DOCUMENTO', 'NUEVA', 'SIN COMPRA')),
  documento text,
  tipo_documento text,
  fecha_documento timestamp,
  proveedor numeric,
  forma_pago text,
  valor_total numeric,
  descripcion text,
  tipo_transaccion numeric,
  modulo_factura numeric,
  usuario text,
  fecha_ingreso timestamp,
  estado text,
  clasificacion numeric,
  usuario_modifica text,
  fecha_modifica timestamp,
  tipo_compra text,
  bodega numeric,
  total_nc numeric,
  bonificaciones numeric,
  descuentos numeric,
  total_sin_desctos numeric,
  empresa numeric,
  completada text,
  descuentos_nd numeric,
  fecha_contabilizacion timestamp,
  fecha_conta_anula timestamp,
  serie_documento text,
  compra_ref numeric,
  valor_total_mi numeric,
  moneda_integracion numeric,
  valor_cambio numeric,
  forma_compra text,
  valor_retencion numeric,
  calcular_retencion text,
  subtotal numeric,
  proyecto numeric,
  creado_por uuid, creado_por_nombre text, creado_en timestamptz default now(),
  modificado_por uuid, modificado_por_nombre text, modificado_en timestamptz,
  unique (localidad_id, compra_anterior)
);
