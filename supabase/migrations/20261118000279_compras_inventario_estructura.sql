-- Script 279 · Organización 4 (Tecnoalsa): compras de inventario del sistema anterior, de «ACT_COMPRAS_MED (INVENTARIO).xlsx» (262 compras,
--   2024-03-27 a 2026-11-14) y «ACT_DETALLE_COMPRAS_MED.xlsx» (1067 artículos), lote del 05-11 al 17-11-2026.
--   Para la organización 4 no se habían migrado (el lote al 04-11-2026 solo traía las compras varias, scripts 229 y 275). Lógica de los scripts 89 y 90 (organización 3):
--   · Cada compra de inventario es el ingreso a bodega de una compra cuyo registro contable es una compra varia ya migrada: COMPRA_REF es el número de esa
--     compra varia (252 compras; 5 con el documento escrito distinto en las dos: 8→17, 49→324, 95→605, 121→741, 232→1657). Sin COMPRA_REF se busca la compra varia con el mismo
--     proveedor, tipo, serie y documento (2). Sus artículos van a esa compra (compra_articulos); la compra varia no se modifica.
--   · Sin compra varia y con valor (4): se crea la compra con origen_anterior = 'MEDICAMENTOS' y su número del sistema anterior en compra_anterior;
--     su número en el sistema va después del último de la localidad (el script 275 las mueve si un lote nuevo de compras varias usa ese número).
--   · Sin compra varia y sin valor (4: 15 (0), 125 (0), 126 (0), 176 (0)): el sistema exige valor mayor que 0;
--     el encabezado queda en la tabla nueva sin compra y sus 2 artículos no se cargan.
--   · Tabla nueva compras_inventario_anteriores: el encabezado completo del sistema anterior (36 columnas con datos, con su nombre original en minúsculas),
--     ligado a su compra (compra_id) y con el tipo de vínculo.
--   · Artículos: producto (por CODIGO_PRODUCTO o por su número anterior, script 228), LOTE = serie, cantidad, costo unitario en quetzales (COSTO_UNITARIO;
--     el de moneda internacional en costo_unitario_mi), descuento, fechas de fabricación y vencimiento, EXENTO_IVA, INCLUIR_COMPRA, REGALIAS, INVENTARIADA.
--     Columnas nuevas en compra_articulos: costo_total_anterior (COSTO_TOTAL del archivo; el costo total lo calcula la base de datos) y compra_inventario_anterior
--     (número de la compra de inventario). 1 compras varias reciben artículos de más de una compra de inventario: la segunda usa las líneas 1001 en adelante.
--   · NO se mueve el inventario: el kardex ya se migró completo (scripts 272 y 294); los artículos quedan marcados como «inventariados» según INVENTARIADA.
--   Se ejecuta después de los scripts 228, 229 y 275. Se puede ejecutar de nuevo: actualiza.
