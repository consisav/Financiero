-- Compras · Procesos y Facturación/Ventas · Procesos · «Carga Facturas SAT»: carga el archivo de facturas recibidas que se descarga del portal de la SAT
-- (.xls / .xlsx / .csv), con la clasificación y la cuenta contable de cada factura, y genera con ellas las compras
-- (o los documentos de una subcaja chica).
--   cargas_sat: cada archivo cargado (empresa, archivo, fecha, usuario y, si va a caja, la subcaja destino).
--   carga_sat_lineas: cada factura del archivo con todas sus columnas; las columnas que no están definidas quedan en
--   «extras». Una factura que se vuelve a cargar (misma autorización en la empresa) solo se actualiza.
--   generar_facturas_sat(carga): crea la compra (con su detalle contable) o el documento de caja de cada factura
--   vigente y clasificada; si la compra ya existe (mismo NIT, serie y número) solo la enlaza.
--   reversar_facturas_sat(carga): quita lo que generó la carga (si no tiene partida, pagos ni está liquidado). Corre con
--   permisos propios (las compras no se borran desde la aplicación) después de validar el permiso del usuario.
-- Se ejecuta después del script 138.

create table if not exists public.cargas_sat (
  id bigint generated by default as identity primary key,
  organizacion_id bigint not null references public.organizaciones(id),
  localidad_id bigint not null references public.localidades(id),
  numero integer not null default 0,
  archivo text,
  fecha date not null default current_date,
  usuario text,
  caja_periodo_id bigint references public.caja_periodos(id) on delete set null,
  estado text not null default 'CARGADA' check (estado in ('CARGADA', 'GENERADA')),
  creado_por uuid, creado_por_nombre text, creado_en timestamptz default now(),
  modificado_por uuid, modificado_por_nombre text, modificado_en timestamptz
);
create index if not exists cargas_sat_localidad on public.cargas_sat (localidad_id, numero);

create table if not exists public.carga_sat_lineas (
  id bigint generated by default as identity primary key,
  carga_id bigint not null references public.cargas_sat(id) on delete cascade,
  localidad_id bigint not null references public.localidades(id),
  linea integer not null default 0,
  fecha_emision timestamptz,
  numero_autorizacion text not null,
  tipo_dte text,
  serie text,
  numero text,
  nit_emisor text,
  nombre_emisor text,
  clasificacion_emisor text,
  exportacion text,
  ubicacion_temporal text,
  codigo_establecimiento text,
  nombre_establecimiento text,
  id_receptor text,
  nombre_receptor text,
  nit_certificador text,
  nombre_certificador text,
  estado text,
  moneda text,
  gran_total numeric(16,6) not null default 0,
  iva numeric(18,10) not null default 0,
  anulada boolean not null default false,
  fecha_anulacion timestamptz,
  petroleo numeric(16,6) not null default 0,
  turismo_hospedaje numeric(16,6) not null default 0,
  turismo_pasaje numeric(16,6) not null default 0,
  timbre_prensa numeric(16,6) not null default 0,
  bomberos numeric(16,6) not null default 0,
  tasa_municipal numeric(16,6) not null default 0,
  bebidas_alcohol numeric(16,6) not null default 0,
  tabaco numeric(16,6) not null default 0,
  cemento numeric(16,6) not null default 0,
  bebidas_no_alcohol numeric(16,6) not null default 0,
  tarifa_portuaria numeric(16,6) not null default 0,
  clasificacion text,
  clasificacion_id bigint references public.clasificaciones_compra(id),
  cuenta_codigo text,
  cuenta_id bigint references public.cuentas(id),
  observaciones text,
  extras jsonb,
  generado boolean not null default false,
  compra_id bigint references public.compras(id) on delete set null,
  caja_documento_id bigint references public.caja_documentos(id) on delete set null,
  resultado text,
  creado_por uuid, creado_por_nombre text, creado_en timestamptz default now(),
  modificado_por uuid, modificado_por_nombre text, modificado_en timestamptz,
  unique (localidad_id, numero_autorizacion)
);
create index if not exists carga_sat_lineas_carga on public.carga_sat_lineas (carga_id, linea);

