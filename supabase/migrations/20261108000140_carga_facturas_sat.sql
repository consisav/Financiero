-- Número de carga por empresa, usuario y empresa de la subcaja.
create or replace function public.preparar_carga_sat() returns trigger
language plpgsql set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    perform pg_advisory_xact_lock(4830, new.localidad_id::integer);
    new.numero := coalesce((select max(numero) from public.cargas_sat where localidad_id = new.localidad_id), 0) + 1;
    new.usuario := coalesce((select upper(p.usuario) from public.perfiles p where p.id = (select auth.uid())), 'SISTEMA');
  else
    new.organizacion_id := old.organizacion_id; new.localidad_id := old.localidad_id;
    new.numero := old.numero; new.usuario := old.usuario;
  end if;
  if new.caja_periodo_id is not null and not exists (select 1 from public.caja_periodos where id = new.caja_periodo_id and localidad_id = new.localidad_id) then
    raise exception 'La subcaja no es de la empresa de la carga.';
  end if;
  new.archivo := nullif(trim(new.archivo), '');
  return new;
end;
$$;
drop trigger if exists cargas_sat_preparar on public.cargas_sat;
create trigger cargas_sat_preparar before insert or update on public.cargas_sat for each row execute function public.preparar_carga_sat();
drop trigger if exists cargas_sat_auditar on public.cargas_sat;
create trigger cargas_sat_auditar before insert or update on public.cargas_sat for each row execute function public.auditar();

-- Línea: empresa de la carga; la clasificación (siglas o código) y la cuenta (código) del archivo se buscan en los
-- catálogos; una línea ya generada conserva sus datos de origen.
create or replace function public.preparar_carga_sat_linea() returns trigger
language plpgsql set search_path = '' as $$
declare
  c public.cargas_sat;
begin
  select * into c from public.cargas_sat where id = new.carga_id;
  new.localidad_id := c.localidad_id;
  new.clasificacion := nullif(upper(trim(new.clasificacion)), '');
  new.cuenta_codigo := nullif(replace(trim(new.cuenta_codigo), ' ', ''), '');
  new.observaciones := nullif(trim(new.observaciones), '');
  new.nit_emisor := nullif(upper(replace(trim(new.nit_emisor), '-', '')), '');
  if new.clasificacion_id is null and new.clasificacion is not null then
    select k.id into new.clasificacion_id from public.clasificaciones_compra k
    where k.activo and (upper(k.siglas) = new.clasificacion or k.codigo::text = new.clasificacion or upper(k.nombre) = new.clasificacion)
    order by (upper(k.siglas) = new.clasificacion) desc, k.codigo limit 1;
  end if;
  if new.clasificacion_id is not null then
    select coalesce(nullif(k.siglas, ''), k.codigo::text) into new.clasificacion from public.clasificaciones_compra k where k.id = new.clasificacion_id;
  end if;
  if new.cuenta_id is null and new.cuenta_codigo is not null then
    select x.id into new.cuenta_id from public.cuentas x join public.catalogos_cuentas k on k.id = x.catalogo_id
    where k.localidad_id = c.localidad_id and replace(x.codigo, '.', '') = replace(new.cuenta_codigo, '.', '')
    order by k.activo desc, k.version desc limit 1;
  end if;
  if new.cuenta_id is not null then
    if not exists (select 1 from public.cuentas x join public.catalogos_cuentas k on k.id = x.catalogo_id where x.id = new.cuenta_id and k.localidad_id = c.localidad_id) then raise exception 'La cuenta de la factura % no es del catálogo de la empresa.', new.numero; end if;
    select x.codigo into new.cuenta_codigo from public.cuentas x where x.id = new.cuenta_id;
  end if;
  if tg_op = 'UPDATE' and old.generado and current_setting('fin.sat', true) is distinct from 'si' then
    new.generado := true; new.compra_id := old.compra_id; new.caja_documento_id := old.caja_documento_id;
  end if;
  return new;
end;
$$;
drop trigger if exists carga_sat_lineas_preparar on public.carga_sat_lineas;
create trigger carga_sat_lineas_preparar before insert or update on public.carga_sat_lineas for each row execute function public.preparar_carga_sat_linea();
drop trigger if exists carga_sat_lineas_auditar on public.carga_sat_lineas;
create trigger carga_sat_lineas_auditar before insert or update on public.carga_sat_lineas for each row execute function public.auditar();

-- Cuenta de movimiento (sin cuentas hijas) del catálogo vigente de la empresa cuyo nombre cumple el patrón.
create or replace function public.cuenta_sat(p_loc bigint, p_patron text, p_patron2 text default null) returns bigint
language sql stable set search_path = '' as $$
  select x.id from public.cuentas x join public.catalogos_cuentas k on k.id = x.catalogo_id
  where k.localidad_id = p_loc and x.nombre ilike p_patron and (p_patron2 is null or x.nombre ~* p_patron2)
    and x.vigente and not exists (select 1 from public.cuentas h where h.cuenta_mayor_id = x.id)
  order by k.activo desc, k.version desc, x.codigo limit 1;
$$;

create or replace function public.generar_facturas_sat(p_carga bigint) returns jsonb
language plpgsql set search_path = '' as $$
declare
  c public.cargas_sat;
  l public.carga_sat_lineas;
  p public.proveedores;
  k public.clasificaciones_compra;
  v_gen integer := 0; v_ya integer := 0; v_omit integer := 0; v_err integer := 0; v_anul integer := 0;
  v_tipo text; v_tipo_id bigint; v_moneda bigint; v_compra public.compras; v_doc bigint; v_otros numeric; v_fecha date;
  v_gasto bigint; v_iva_cta bigint; v_pagar bigint; v_existe bigint; v_caja_tipo text; v_caja_clas text;
begin
  if not public.puede_editar_catalogos() then raise exception 'No tienes permiso para generar facturas.'; end if;
  perform set_config('fin.sat', 'si', true);
  select * into c from public.cargas_sat where id = p_carga;
  if c.id is null then raise exception 'La carga no existe.'; end if;
  v_iva_cta := public.cuenta_sat(c.localidad_id, '%IVA%', '(COBRAR|CR[EÉ]DITO)');
  if v_iva_cta is null then v_iva_cta := public.cuenta_sat(c.localidad_id, '%IVA%'); end if;
  for l in select * from public.carga_sat_lineas where carga_id = p_carga and not generado order by linea loop
    begin
      if l.anulada or upper(coalesce(l.estado, 'VIGENTE')) <> 'VIGENTE' then
        update public.carga_sat_lineas set resultado = 'Anulada en la SAT: no se genera.' where id = l.id; v_anul := v_anul + 1; continue;
      end if;
      if upper(coalesce(l.tipo_dte, '')) in ('NCRE', 'NDEB', 'NABN') then
        update public.carga_sat_lineas set resultado = 'Es una nota: regístrala en Notas crédito compras.' where id = l.id; v_omit := v_omit + 1; continue;
      end if;
      if l.clasificacion_id is null then
        update public.carga_sat_lineas set resultado = 'Falta la clasificación.' where id = l.id; v_omit := v_omit + 1; continue;
      end if;
      select * into k from public.clasificaciones_compra where id = l.clasificacion_id;
      select * into p from public.proveedores where localidad_id = c.localidad_id and upper(replace(nit, '-', '')) = l.nit_emisor
      order by (estado = 'ACTIVO') desc, id limit 1;
      v_gasto := coalesce(l.cuenta_id, p.cuenta_gasto_id);
      v_fecha := (l.fecha_emision at time zone 'America/Guatemala')::date;
      -- Impuestos que no llevan IVA (no son parte de la base): petróleo, timbre, bomberos, tasa municipal, bebidas,
      -- tabaco, cemento y tarifa portuaria.
      v_otros := round(l.petroleo + l.timbre_prensa + l.bomberos + l.tasa_municipal + l.bebidas_alcohol + l.tabaco + l.cemento + l.bebidas_no_alcohol + l.tarifa_portuaria, 2);

      if c.caja_periodo_id is not null then
        -- Documento de la subcaja chica.
        select d.id into v_existe from public.caja_documentos d where d.periodo_id = c.caja_periodo_id
          and d.nit is not distinct from l.nit_emisor and coalesce(d.serie, '') = upper(coalesce(l.serie, '')) and d.documento = upper(l.numero) limit 1;
        if v_existe is not null then
          update public.carga_sat_lineas set generado = true, caja_documento_id = v_existe, resultado = 'Ya estaba en la subcaja: solo se enlazó.' where id = l.id;
          v_ya := v_ya + 1; continue;
        end if;
        if v_gasto is null then
          update public.carga_sat_lineas set resultado = 'Falta la cuenta contable.' where id = l.id; v_omit := v_omit + 1; continue;
        end if;
        v_caja_tipo := case upper(l.tipo_dte) when 'FPEQ' then 'FACTURA PEQUEÑO CONTRIBUYENTE' when 'FESP' then 'FACTURA ESPECIAL' when 'RECI' then 'RECIBO' else 'FACTURA ELECTRÓNICA' end;
        v_caja_clas := case when k.nombre ilike 'SERVICIO%' then 'SERVICIOS' when k.nombre ilike 'COMBUSTIBLE%' then 'COMBUSTIBLE'
                            when k.nombre ilike 'IMPORTACI%' then 'IMPORTACIÓN' when k.nombre ilike 'BIENES%' then 'BIENES' else 'OTROS' end;
        insert into public.caja_documentos (periodo_id, serie, documento, tipo_documento, tipo_documento_id, fecha, nit, proveedor_codigo, proveedor_id, proveedor_nombre,
          moneda_id, clasificacion, clasificacion_id, total, exento, inguat, timbre_prensa, porcentaje_iva, justificacion, cuenta_gasto_id, contable)
        values (c.caja_periodo_id, l.serie, l.numero, v_caja_tipo,
          (select t.id from public.tipos_documento_compra t where t.nombre = v_caja_tipo limit 1), v_fecha, l.nit_emisor, p.codigo::text, p.id,
          coalesce(p.nombre_fiscal, p.nombre_comercial, l.nombre_emisor),
          coalesce((select m.id from public.monedas m where upper(m.iso) = upper(l.moneda) limit 1), (select m.id from public.monedas m order by m.codigo limit 1)),
          v_caja_clas, k.id, round(l.gran_total, 2),
          case when k.aplica_iva or upper(l.tipo_dte) = 'FPEQ' then round(l.petroleo + l.bomberos + l.tasa_municipal + l.bebidas_alcohol + l.tabaco + l.cemento + l.bebidas_no_alcohol + l.tarifa_portuaria, 2) else round(l.gran_total - l.turismo_hospedaje - l.timbre_prensa, 2) end,
          round(l.turismo_hospedaje, 2), round(l.timbre_prensa, 2), case when k.aplica_iva then 12 else 0 end,
          coalesce(l.observaciones, l.nombre_emisor), v_gasto, true)
        returning id into v_doc;
        update public.carga_sat_lineas set generado = true, caja_documento_id = v_doc, resultado = 'Documento de caja generado.' where id = l.id;
        v_gen := v_gen + 1;
      else
        -- Compra con su detalle contable.
        select x.id into v_existe from public.compras x where x.localidad_id = c.localidad_id and x.estado <> 'ANULADA'
          and x.nit is not distinct from l.nit_emisor and coalesce(x.serie, '') = upper(coalesce(l.serie, '')) and x.documento = upper(l.numero) limit 1;
        if v_existe is not null then
          update public.carga_sat_lineas set generado = true, compra_id = v_existe, resultado = 'La compra ya existía: solo se enlazó.' where id = l.id;
          v_ya := v_ya + 1; continue;
        end if;
        if v_gasto is null then
          update public.carga_sat_lineas set resultado = 'Falta la cuenta contable (ni el archivo ni el proveedor la tienen).' where id = l.id; v_omit := v_omit + 1; continue;
        end if;
        v_tipo := case upper(l.tipo_dte) when 'FPEQ' then 'FACTURA PEQUEÑO CONTRIBUYENTE' when 'FESP' then 'FACTURA ESPECIAL' when 'RECI' then 'RECIBO' else 'FACTURA ELECTRÓNICA' end;
        select t.id into v_tipo_id from public.tipos_documento_compra t where t.nombre = v_tipo limit 1;
        v_moneda := coalesce((select m.id from public.monedas m where upper(m.iso) = upper(l.moneda) limit 1), (select m.id from public.monedas m order by m.codigo limit 1));
        -- Cuenta por pagar: la de la última compra de ese NIT, la más usada en la empresa o la de proveedores varios.
        v_pagar := coalesce(
          (select x.cuenta_pagar_id from public.compras x where x.localidad_id = c.localidad_id and x.nit = l.nit_emisor and x.cuenta_pagar_id is not null order by x.id desc limit 1),
          (select x.cuenta_pagar_id from public.compras x where x.localidad_id = c.localidad_id and x.cuenta_pagar_id is not null group by 1 order by count(*) desc limit 1),
          public.cuenta_sat(c.localidad_id, 'PROVEEDORES VARIOS%'), public.cuenta_sat(c.localidad_id, 'PROVEEDORES%'));
        insert into public.compras (organizacion_id, localidad_id, tipo_documento_id, tipo_dte, serie, documento, fecha_documento, fecha_ingreso,
          proveedor_id, proveedor_codigo, proveedor_nombre, nit, descripcion, moneda_id, tipo_cambio, valor_total, clasificacion_id,
          aplica_inguat, inguat, turismo_itp, exento, dias_credito, forma_pago, cuenta_pagar_id, mes_presentacion, anio_presentacion, origen_anterior)
        values (c.organizacion_id, c.localidad_id, v_tipo_id, v_tipo, l.serie, l.numero, v_fecha, current_date,
          p.id, p.codigo::text, coalesce(p.nombre_fiscal, p.nombre_comercial, l.nombre_emisor), l.nit_emisor,
          coalesce(l.observaciones, 'CARGA SAT ' || l.numero_autorizacion), v_moneda, 1, round(l.gran_total, 2), k.id,
          l.turismo_hospedaje > 0, round(l.turismo_hospedaje, 2), round(l.turismo_pasaje, 2), v_otros,
          coalesce(p.dias_credito, 0), coalesce(nullif(p.forma_pago, ''), 'CHEQUE'), v_pagar,
          extract(month from v_fecha)::integer, extract(year from v_fecha)::integer, 'CARGA SAT')
        returning * into v_compra;
        insert into public.compra_lineas (compra_id, linea, cuenta_id, debe, haber)
        select v_compra.id, row_number() over (order by o), cta, d, h from (values
          (1, v_gasto, v_compra.valor_total - v_compra.iva, 0::numeric),
          (2, v_iva_cta, v_compra.iva, 0::numeric),
          (3, v_pagar, 0::numeric, v_compra.valor_total)) as x(o, cta, d, h)
        where cta is not null and (d <> 0 or h <> 0);
        update public.carga_sat_lineas set generado = true, compra_id = v_compra.id,
          resultado = 'Compra ' || v_compra.numero || ' generada.' || case when v_pagar is null then ' Falta la cuenta por pagar en su detalle contable.' when v_compra.iva > 0 and v_iva_cta is null then ' Falta la cuenta de IVA en su detalle contable.' else '' end
        where id = l.id;
        v_gen := v_gen + 1;
      end if;
    exception when others then
      update public.carga_sat_lineas set resultado = 'Error: ' || sqlerrm where id = l.id;
      v_err := v_err + 1;
    end;
  end loop;
  update public.cargas_sat set estado = case when exists (select 1 from public.carga_sat_lineas where carga_id = p_carga and generado) then 'GENERADA' else 'CARGADA' end where id = p_carga;
  return jsonb_build_object('generadas', v_gen, 'enlazadas', v_ya, 'omitidas', v_omit, 'errores', v_err, 'anuladas', v_anul);
end;
$$;

create or replace function public.reversar_facturas_sat(p_carga bigint) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare
  l record;
  v_rev integer := 0; v_quedan integer := 0;
begin
  if not public.puede_editar_catalogos() then raise exception 'No tienes permiso para reversar facturas.'; end if;
  perform set_config('fin.sat', 'si', true);
  for l in select s.*, x.partida_id, x.estado as estado_compra, x.contrasena_id, x.origen_anterior as origen_compra,
                  d.periodo_id, (select pp.estado from public.caja_periodos pp where pp.id = d.periodo_id) as estado_caja
           from public.carga_sat_lineas s left join public.compras x on x.id = s.compra_id left join public.caja_documentos d on d.id = s.caja_documento_id
           where s.carga_id = p_carga and s.generado loop
    begin
      if l.compra_id is not null and l.origen_compra = 'CARGA SAT' then
        if l.partida_id is not null then raise exception 'la compra ya tiene partida'; end if;
        if exists (select 1 from public.movimiento_documentos d join public.movimientos_bancarios m on m.id = d.movimiento_id and m.estado = 'ACTIVO'
                   where d.compra_id = l.compra_id and d.abono_compra <> 0) then raise exception 'la compra ya tiene pagos'; end if;
        if l.contrasena_id is not null then raise exception 'la compra ya tiene contraseña de pago'; end if;
        delete from public.compra_lineas where compra_id = l.compra_id;
        delete from public.compra_items where compra_id = l.compra_id;
        delete from public.compras where id = l.compra_id;
      elsif l.caja_documento_id is not null and l.resultado not like 'Ya estaba%' then
        if l.estado_caja = 'LIQUIDADA' then raise exception 'la subcaja ya está liquidada'; end if;
        delete from public.caja_documentos where id = l.caja_documento_id;
      end if;
      update public.carga_sat_lineas set generado = false, compra_id = null, caja_documento_id = null, resultado = null where id = l.id;
      v_rev := v_rev + 1;
    exception when others then
      update public.carga_sat_lineas set resultado = 'No se reversó: ' || sqlerrm || '.' where id = l.id;
      v_quedan := v_quedan + 1;
    end;
  end loop;
  update public.cargas_sat set estado = case when exists (select 1 from public.carga_sat_lineas where carga_id = p_carga and generado) then 'GENERADA' else 'CARGADA' end where id = p_carga;
  return jsonb_build_object('reversadas', v_rev, 'quedan', v_quedan);
end;
$$;

grant execute on function public.generar_facturas_sat(bigint), public.reversar_facturas_sat(bigint), public.cuenta_sat(bigint, text, text) to authenticated;

-- ---------- Seguridad ----------
do $$
declare t text;
begin
  foreach t in array array['cargas_sat', 'carga_sat_lineas'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists "%s: leer" on public.%I', t, t);
    execute format('create policy "%s: leer" on public.%I for select to authenticated using (public.usuario_activo())', t, t);
    execute format('drop policy if exists "%s: crear" on public.%I', t, t);
    execute format('create policy "%s: crear" on public.%I for insert to authenticated with check (public.puede_editar_catalogos())', t, t);
    execute format('drop policy if exists "%s: modificar" on public.%I', t, t);
    execute format('create policy "%s: modificar" on public.%I for update to authenticated using (public.puede_editar_catalogos()) with check (public.puede_editar_catalogos())', t, t);
    execute format('drop policy if exists "%s: quitar" on public.%I', t, t);
    execute format('create policy "%s: quitar" on public.%I for delete to authenticated using (public.puede_editar_catalogos())', t, t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
  end loop;
end;
$$;

-- ---------- Menú: Compras · Procesos y Facturación/Ventas · Procesos ----------
do $$
declare v_mod bigint; v_ref bigint; v_id bigint; r record;
begin
  for r in select * from (values ('facturas-compra'), ('facturas-ventas')) as x(ref) loop
    select id, modulo_id into v_ref, v_mod from public.opciones_sistema where grupo = 'registros' and clave = r.ref order by id limit 1;
    if v_ref is null then raise notice 'No existe la opción %.', r.ref; continue; end if;
    if not exists (select 1 from public.opciones_sistema where modulo_id = v_mod and clave = 'carga-facturas-sat') then
      insert into public.opciones_sistema (modulo_id, grupo, subgrupo, clave, nombre, orden)
      values (v_mod, 'procesos', 'Procesos', 'carga-facturas-sat', 'Carga Facturas SAT', (select max(orden) from public.opciones_sistema where modulo_id = v_mod) + 1)
      returning id into v_id;
      insert into public.rol_accesos (rol_id, opcion_id, ver, crear, modificar, anular, imprimir)
      select a.rol_id, v_id, a.ver, a.crear, a.modificar, a.anular, a.imprimir from public.rol_accesos a where a.opcion_id = v_ref on conflict do nothing;
    end if;
  end loop;
  raise notice 'Carga Facturas SAT instalada en Compras y en Facturación/Ventas.';
end;
$$;
