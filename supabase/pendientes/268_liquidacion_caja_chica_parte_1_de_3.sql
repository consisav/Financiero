-- Script 268 · Organizaciones 4 (Tecnoalsa) y 7 (AAPOS): documentos con que se liquidaron o reintegraron las subcajas de caja chica, de
--   «CON_LIQUIDACION_CAJA_CHICA.xlsx» (1360 registros: 4-01: 1177, 7-01: 183).
--   Tipos: 4 POL (póliza, aplicación L): 148, 4 NOD (nota de débito, aplicación L): 1029, 7 CHQ (cheque, aplicación L): 98, 7 DEP (depósito, aplicación R): 64, 7 NOD (nota de débito, aplicación L): 7, 7 NOC (nota de crédito, aplicación R): 14.
--   La subcaja guarda un solo documento por fondo (anticipo, adelanto y liquidación), y este archivo trae varios por subcaja: van en la tabla
--   nueva caja_liquidacion_documentos, con todas sus columnas: caja y subcaja (ligadas a las del script 254), tipo de documento, cuenta bancaria,
--   documento, correlativo, monto, tipo de aplicación (L = liquidación, R = reintegro), año y mes de la póliza, año y mes de la caja y fecha de ingreso.
--   Cada documento se liga a su movimiento bancario (nota, cheque o depósito de los scripts 257 a 259, por cuenta y número) o a su partida
--   (póliza: año, mes y número, script 266). Lo que no se encuentra queda con su número. CUENTA_BANCARIA 0 = sin cuenta (pólizas).
--   1 depósito de AAPOS (caja 735) no trae subcaja: queda con subcaja 0.
--   CONTIENE NÚMEROS DE CUENTAS BANCARIAS: las partes con datos no se suben al repositorio (la parte 1, solo estructura, sí).
--   Se ejecuta después de los scripts 254, 257 a 259 y 266. Se puede ejecutar de nuevo: actualiza.
-- Parte 1 de 3: estructura.
set lock_timeout = '20s';

create table if not exists public.caja_liquidacion_documentos (
  id bigint generated by default as identity primary key,
  organizacion_id bigint not null references public.organizaciones(id),
  localidad_id bigint not null references public.localidades(id),
  caja_id bigint references public.cajas_chicas(id) on delete set null,
  caja_periodo_id bigint references public.caja_periodos(id) on delete set null,
  caja_anterior integer not null,
  subcaja_anterior integer not null default 0,
  tipo_documento text not null,
  cuenta_bancaria text not null default '',
  cuenta_bancaria_id bigint references public.cuentas_bancarias(id) on delete set null,
  documento integer,
  correlativo integer,
  monto numeric(18, 2) not null default 0,
  tipo_aplicacion text,
  anio integer,
  mes integer,
  anio_caja integer,
  mes_caja integer,
  fecha_ingresa timestamp,
  movimiento_id bigint references public.movimientos_bancarios(id) on delete set null,
  partida_id bigint references public.partidas(id) on delete set null,
  origen_anterior text,
  creado_por uuid, creado_por_nombre text, creado_en timestamptz default now(),
  modificado_por uuid, modificado_por_nombre text, modificado_en timestamptz,
  unique (localidad_id, caja_anterior, subcaja_anterior, tipo_documento, cuenta_bancaria, documento, correlativo)
);
create index if not exists caja_liquidacion_documentos_periodo on public.caja_liquidacion_documentos (caja_periodo_id);
drop trigger if exists caja_liquidacion_documentos_auditar on public.caja_liquidacion_documentos;
create trigger caja_liquidacion_documentos_auditar before insert or update on public.caja_liquidacion_documentos for each row execute function public.auditar();
alter table public.caja_liquidacion_documentos enable row level security;
drop policy if exists "caja_liquidacion_documentos: leer" on public.caja_liquidacion_documentos;
create policy "caja_liquidacion_documentos: leer" on public.caja_liquidacion_documentos for select to authenticated using (public.usuario_activo());
drop policy if exists "caja_liquidacion_documentos: crear" on public.caja_liquidacion_documentos;
create policy "caja_liquidacion_documentos: crear" on public.caja_liquidacion_documentos for insert to authenticated with check (public.puede_editar_catalogos());
drop policy if exists "caja_liquidacion_documentos: modificar" on public.caja_liquidacion_documentos;
create policy "caja_liquidacion_documentos: modificar" on public.caja_liquidacion_documentos for update to authenticated using (public.puede_editar_catalogos()) with check (public.puede_editar_catalogos());
drop policy if exists "caja_liquidacion_documentos: quitar" on public.caja_liquidacion_documentos;
create policy "caja_liquidacion_documentos: quitar" on public.caja_liquidacion_documentos for delete to authenticated using (public.puede_editar_catalogos());
grant select, insert, update, delete on public.caja_liquidacion_documentos to authenticated;
notify pgrst, 'reload schema';
