WHENEVER SQLERROR EXIT SQL.SQLCODE

-- ---------------------------------------------------------------------
-- Cuentas por cobrar / pagar
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_TERCEROS NOCACHE;
CREATE TABLE TERCEROS (
  ID_TERCERO    NUMBER(12)     DEFAULT SEQ_TERCEROS.NEXTVAL PRIMARY KEY,
  TIPO          VARCHAR2(1)    NOT NULL CONSTRAINT CK_TERCEROS_TIPO CHECK (TIPO IN ('C','P','A')), -- Cliente, Proveedor, Ambos
  NIT           VARCHAR2(20),
  NOMBRE        VARCHAR2(200)  NOT NULL,
  EMAIL         VARCHAR2(200),
  TELEFONO      VARCHAR2(30),
  DIRECCION     VARCHAR2(400),
  DIAS_CREDITO  NUMBER(4)      DEFAULT 0 NOT NULL,
  ACTIVO        CHAR(1)        DEFAULT 'S' NOT NULL CONSTRAINT CK_TERCEROS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_TERCEROS_NIT ON TERCEROS (NIT);

CREATE SEQUENCE SEQ_CUENTAS_BANCARIAS NOCACHE;
CREATE TABLE CUENTAS_BANCARIAS (
  ID_CUENTA      NUMBER(12)    DEFAULT SEQ_CUENTAS_BANCARIAS.NEXTVAL PRIMARY KEY,
  BANCO          VARCHAR2(100) NOT NULL,
  NUMERO_CUENTA  VARCHAR2(40)  NOT NULL CONSTRAINT UQ_CUENTAS_NUMERO UNIQUE,
  TIPO           VARCHAR2(10)  NOT NULL CONSTRAINT CK_CUENTAS_TIPO CHECK (TIPO IN ('MONETARIA','AHORRO','CAJA')),
  MONEDA         CHAR(3)       DEFAULT 'GTQ' NOT NULL,
  SALDO_INICIAL  NUMBER(14,2)  DEFAULT 0 NOT NULL,
  ACTIVO         CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT CK_CUENTAS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE SEQ_MOVIMIENTOS_BANCARIOS NOCACHE;
CREATE TABLE MOVIMIENTOS_BANCARIOS (
  ID_MOVIMIENTO  NUMBER(12)    DEFAULT SEQ_MOVIMIENTOS_BANCARIOS.NEXTVAL PRIMARY KEY,
  ID_CUENTA      NUMBER(12)    NOT NULL CONSTRAINT FK_MOVBAN_CUENTA REFERENCES CUENTAS_BANCARIAS,
  FECHA          DATE          NOT NULL,
  TIPO           VARCHAR2(7)   NOT NULL CONSTRAINT CK_MOVBAN_TIPO CHECK (TIPO IN ('DEBITO','CREDITO')),
  MONTO          NUMBER(14,2)  NOT NULL CONSTRAINT CK_MOVBAN_MONTO CHECK (MONTO > 0),
  REFERENCIA     VARCHAR2(60),
  DESCRIPCION    VARCHAR2(400),
  CONCILIADO     CHAR(1)       DEFAULT 'N' NOT NULL CONSTRAINT CK_MOVBAN_CONC CHECK (CONCILIADO IN ('S','N')),
  CREADO_EN      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_MOVBAN_CUENTA_FECHA ON MOVIMIENTOS_BANCARIOS (ID_CUENTA, FECHA);

CREATE SEQUENCE SEQ_DOCUMENTOS NOCACHE;
CREATE TABLE DOCUMENTOS_CXC_CXP (
  ID_DOCUMENTO       NUMBER(12)    DEFAULT SEQ_DOCUMENTOS.NEXTVAL PRIMARY KEY,
  ID_TERCERO         NUMBER(12)    NOT NULL CONSTRAINT FK_DOC_TERCERO REFERENCES TERCEROS,
  TIPO               VARCHAR2(3)   NOT NULL CONSTRAINT CK_DOC_TIPO CHECK (TIPO IN ('CXC','CXP')),
  SERIE              VARCHAR2(20),
  NUMERO             VARCHAR2(40)  NOT NULL,
  FECHA_EMISION      DATE          NOT NULL,
  FECHA_VENCIMIENTO  DATE,
  MONEDA             CHAR(3)       DEFAULT 'GTQ' NOT NULL,
  TOTAL              NUMBER(14,2)  NOT NULL,
  SALDO              NUMBER(14,2)  NOT NULL,
  ESTADO             VARCHAR2(10)  DEFAULT 'PENDIENTE' NOT NULL
                       CONSTRAINT CK_DOC_ESTADO CHECK (ESTADO IN ('PENDIENTE','PAGADO','ANULADO')),
  DESCRIPCION        VARCHAR2(400),
  CREADO_EN          TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_DOC_NUMERO UNIQUE (ID_TERCERO, TIPO, SERIE, NUMERO)
);
CREATE INDEX IX_DOC_VENCIMIENTO ON DOCUMENTOS_CXC_CXP (TIPO, ESTADO, FECHA_VENCIMIENTO);

CREATE SEQUENCE SEQ_PAGOS NOCACHE;
CREATE TABLE PAGOS_CXC_CXP (
  ID_PAGO        NUMBER(12)    DEFAULT SEQ_PAGOS.NEXTVAL PRIMARY KEY,
  ID_DOCUMENTO   NUMBER(12)    NOT NULL CONSTRAINT FK_PAGO_DOC REFERENCES DOCUMENTOS_CXC_CXP,
  ID_MOVIMIENTO  NUMBER(12)    CONSTRAINT FK_PAGO_MOVBAN REFERENCES MOVIMIENTOS_BANCARIOS,
  FECHA          DATE          NOT NULL,
  MONTO          NUMBER(14,2)  NOT NULL CONSTRAINT CK_PAGO_MONTO CHECK (MONTO > 0),
  REFERENCIA     VARCHAR2(60),
  CREADO_EN      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_PAGO_DOC ON PAGOS_CXC_CXP (ID_DOCUMENTO);
CREATE INDEX IX_PAGO_MOVBAN ON PAGOS_CXC_CXP (ID_MOVIMIENTO);

-- ---------------------------------------------------------------------
-- Presupuesto
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_CENTROS_COSTO NOCACHE;
CREATE TABLE CENTROS_COSTO (
  ID_CENTRO  NUMBER(12)    DEFAULT SEQ_CENTROS_COSTO.NEXTVAL PRIMARY KEY,
  CODIGO     VARCHAR2(20)  NOT NULL CONSTRAINT UQ_CENTROS_CODIGO UNIQUE,
  NOMBRE     VARCHAR2(100) NOT NULL,
  ACTIVO     CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT CK_CENTROS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE SEQ_PRESUPUESTOS NOCACHE;
CREATE TABLE PRESUPUESTOS (
  ID_PRESUPUESTO   NUMBER(12)    DEFAULT SEQ_PRESUPUESTOS.NEXTVAL PRIMARY KEY,
  ID_CENTRO        NUMBER(12)    NOT NULL CONSTRAINT FK_PRES_CENTRO REFERENCES CENTROS_COSTO,
  CUENTA_CONTABLE  VARCHAR2(30)  NOT NULL, -- código de cuenta de la contabilidad existente
  ANIO             NUMBER(4)     NOT NULL,
  MES              NUMBER(2)     NOT NULL CONSTRAINT CK_PRES_MES CHECK (MES BETWEEN 1 AND 12),
  MONTO            NUMBER(14,2)  NOT NULL,
  CREADO_EN        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_PRES UNIQUE (ID_CENTRO, CUENTA_CONTABLE, ANIO, MES)
);

-- ---------------------------------------------------------------------
-- Inventarios (propios de Financiero; la integración con el inventario
-- de la aplicación existente se define cuando se conozcan sus tablas)
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_PRODUCTOS NOCACHE;
CREATE TABLE PRODUCTOS (
  ID_PRODUCTO     NUMBER(12)    DEFAULT SEQ_PRODUCTOS.NEXTVAL PRIMARY KEY,
  CODIGO          VARCHAR2(40)  NOT NULL CONSTRAINT UQ_PRODUCTOS_CODIGO UNIQUE,
  NOMBRE          VARCHAR2(200) NOT NULL,
  UNIDAD          VARCHAR2(20)  DEFAULT 'UNIDAD' NOT NULL,
  COSTO_PROMEDIO  NUMBER(14,4)  DEFAULT 0 NOT NULL,
  ACTIVO          CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT CK_PRODUCTOS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE SEQ_BODEGAS NOCACHE;
CREATE TABLE BODEGAS (
  ID_BODEGA  NUMBER(12)    DEFAULT SEQ_BODEGAS.NEXTVAL PRIMARY KEY,
  CODIGO     VARCHAR2(20)  NOT NULL CONSTRAINT UQ_BODEGAS_CODIGO UNIQUE,
  NOMBRE     VARCHAR2(100) NOT NULL,
  ACTIVO     CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT CK_BODEGAS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE SEQUENCE SEQ_MOVIMIENTOS_INVENTARIO NOCACHE;
CREATE TABLE MOVIMIENTOS_INVENTARIO (
  ID_MOV_INV      NUMBER(12)    DEFAULT SEQ_MOVIMIENTOS_INVENTARIO.NEXTVAL PRIMARY KEY,
  ID_PRODUCTO     NUMBER(12)    NOT NULL CONSTRAINT FK_MOVINV_PRODUCTO REFERENCES PRODUCTOS,
  ID_BODEGA       NUMBER(12)    NOT NULL CONSTRAINT FK_MOVINV_BODEGA REFERENCES BODEGAS,
  FECHA           DATE          NOT NULL,
  TIPO            VARCHAR2(7)   NOT NULL CONSTRAINT CK_MOVINV_TIPO CHECK (TIPO IN ('ENTRADA','SALIDA','AJUSTE')),
  CANTIDAD        NUMBER(14,4)  NOT NULL,
  COSTO_UNITARIO  NUMBER(14,4)  DEFAULT 0 NOT NULL,
  REFERENCIA      VARCHAR2(60),
  CREADO_EN       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_MOVINV_PROD_BOD ON MOVIMIENTOS_INVENTARIO (ID_PRODUCTO, ID_BODEGA, FECHA);
CREATE INDEX IX_MOVINV_BODEGA ON MOVIMIENTOS_INVENTARIO (ID_BODEGA);

-- ---------------------------------------------------------------------
-- Nóminas
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_EMPLEADOS NOCACHE;
CREATE TABLE EMPLEADOS (
  ID_EMPLEADO    NUMBER(12)    DEFAULT SEQ_EMPLEADOS.NEXTVAL PRIMARY KEY,
  CODIGO         VARCHAR2(20)  NOT NULL CONSTRAINT UQ_EMPLEADOS_CODIGO UNIQUE,
  NOMBRE         VARCHAR2(200) NOT NULL,
  DPI            VARCHAR2(13),
  PUESTO         VARCHAR2(100),
  ID_CENTRO      NUMBER(12)    CONSTRAINT FK_EMP_CENTRO REFERENCES CENTROS_COSTO,
  FECHA_INGRESO  DATE          NOT NULL,
  SALARIO_BASE   NUMBER(14,2)  NOT NULL,
  ACTIVO         CHAR(1)       DEFAULT 'S' NOT NULL CONSTRAINT CK_EMPLEADOS_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CREADO_EN      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_EMP_CENTRO ON EMPLEADOS (ID_CENTRO);

CREATE SEQUENCE SEQ_PLANILLAS NOCACHE;
CREATE TABLE PLANILLAS (
  ID_PLANILLA     NUMBER(12)    DEFAULT SEQ_PLANILLAS.NEXTVAL PRIMARY KEY,
  PERIODO_INICIO  DATE          NOT NULL,
  PERIODO_FIN     DATE          NOT NULL,
  DESCRIPCION     VARCHAR2(200),
  ESTADO          VARCHAR2(8)   DEFAULT 'BORRADOR' NOT NULL CONSTRAINT CK_PLANILLAS_ESTADO CHECK (ESTADO IN ('BORRADOR','CERRADA')),
  CREADO_EN       TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT CK_PLANILLAS_PERIODO CHECK (PERIODO_FIN >= PERIODO_INICIO)
);

CREATE SEQUENCE SEQ_PLANILLA_DETALLE NOCACHE;
CREATE TABLE PLANILLA_DETALLE (
  ID_DETALLE   NUMBER(12)    DEFAULT SEQ_PLANILLA_DETALLE.NEXTVAL PRIMARY KEY,
  ID_PLANILLA  NUMBER(12)    NOT NULL CONSTRAINT FK_PLADET_PLANILLA REFERENCES PLANILLAS ON DELETE CASCADE,
  ID_EMPLEADO  NUMBER(12)    NOT NULL CONSTRAINT FK_PLADET_EMPLEADO REFERENCES EMPLEADOS,
  CONCEPTO     VARCHAR2(100) NOT NULL,
  TIPO         VARCHAR2(9)   NOT NULL CONSTRAINT CK_PLADET_TIPO CHECK (TIPO IN ('INGRESO','DESCUENTO')),
  MONTO        NUMBER(14,2)  NOT NULL,
  CREADO_EN    TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_PLADET_PLANILLA ON PLANILLA_DETALLE (ID_PLANILLA);
CREATE INDEX IX_PLADET_EMPLEADO ON PLANILLA_DETALLE (ID_EMPLEADO);

-- ---------------------------------------------------------------------
-- Integraciones (bitácora de intercambios con otros sistemas)
-- ---------------------------------------------------------------------
CREATE SEQUENCE SEQ_INTEGRACIONES_LOG NOCACHE;
CREATE TABLE INTEGRACIONES_LOG (
  ID_LOG     NUMBER(12)     DEFAULT SEQ_INTEGRACIONES_LOG.NEXTVAL PRIMARY KEY,
  SISTEMA    VARCHAR2(50)   NOT NULL,
  OPERACION  VARCHAR2(100)  NOT NULL,
  ESTADO     VARCHAR2(5)    NOT NULL CONSTRAINT CK_INTLOG_ESTADO CHECK (ESTADO IN ('OK','ERROR')),
  MENSAJE    VARCHAR2(4000),
  CREADO_EN  TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL
);
CREATE INDEX IX_INTLOG_SISTEMA ON INTEGRACIONES_LOG (SISTEMA, CREADO_EN);

PROMPT Esquema de Financiero creado.
